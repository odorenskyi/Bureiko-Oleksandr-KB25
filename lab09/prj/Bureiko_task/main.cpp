#include <iostream>
#include <windows.h>
#include "../../../lab08/prj/Modules_Bureiko.h"

using namespace std;

int main() {
    // встановлення кодування для коректного відображення кирилиці в консолі
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    char choice;
    char exit_choice;

    // головний безкінечний цикл програми
    while (true) {
        cout << "\n================ ГОЛОВНЕ МЕНЮ ================\n";
        cout << "d - Розрахунок математичного виразу S (Задача 8.1)\n";
        cout << "g - Розрахунок вартості електроенергії (Задача 9.1)\n";
        cout << "h - Шкала Бофорта: мінімальна швидкість вітру (Задача 9.2)\n";
        cout << "j - Побітовий аналіз числа (Задача 9.3)\n";
        cout << "Оберіть дію: ";
        cin >> choice;

        cout << "----------------------------------------------\n";

        // обробка вибору користувача
        switch (choice) {
            case 'd': {
                double x, y, z;
                cout << "Введіть значення x, y, z (через пробіл, x > 3): ";
                cin >> x >> y >> z;
                cout << "Результат обчислення функції S = " << s_calculation(x, y, z) << "\n";
                break;
            }
            case 'g': {
                double kwh;
                cout << "Введіть обсяг спожитої електроенергії (кВт*год): ";
                cin >> kwh;
                cout << "Сума до сплати: " << calc_electricity_cost(kwh) << " грн\n";
                break;
            }
            case 'h': {
                double v1, v2, v3, v4, v5, v6;
                cout << "Введіть 6 показників швидкості вітру (через пробіл): ";
                cin >> v1 >> v2 >> v3 >> v4 >> v5 >> v6;
                cout << "Мінімальна швидкість за шкалою Бофорта: "
                     << get_min_beaufort(v1, v2, v3, v4, v5, v6) << " балів\n";
                break;
            }
            case 'j': {
                unsigned int N;
                cout << "Введіть натуральне число N (до 500700): ";
                cin >> N;
                cout << "Результат побітового аналізу: " << count_bits_by_condition(N) << "\n";
                break;
            }
            default: {
                // відтворення звукового сигналу (\a) при помилковому введенні
                cout << "\aПОМИЛКА: Невідома команда! Спробуйте ще раз.\n";
                continue; // Повернення на початок циклу без запиту на вихід
            }
        }

        cout << "----------------------------------------------\n";
        cout << "Введіть 'k', 'K' (латиниця) або 'к', 'К' (кирилиця) для виходу з програми.\n";
        cout << "Для повторення введіть будь-який інший символ: ";
        cin >> exit_choice;

        // перевірка умови виходу
        if (exit_choice == 'k' || exit_choice == 'K' || exit_choice == 'к' || exit_choice == 'К') {
            cout << "Роботу програми завершено.\n";
            break; // переривання головного циклу
        }
    }

    return 0;
}
